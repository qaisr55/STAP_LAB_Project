"""Continuous Distribution"""

import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import norm

# 1. Calculate parameters from your clean data
mu = df_clean['age'].mean()
sigma = df_clean['age'].std()

# 2. Generate the normal curve space
x = np.linspace(mu - 4*sigma, mu + 4*sigma, 100)
pdf = norm.pdf(x, mu, sigma)

# 3. Plot the theoretical Normal Distribution
plt.figure(figsize=(8, 5))
# Plotting histogram
plt.hist(df_clean['age'], bins=20, density=True, alpha=0.6, color='purple', label='Actual Data')
# Plotting theoretical line
plt.plot(x, pdf, 'r-', linewidth=2, label='Normal Curve Fit')

plt.xlabel('Age')
plt.ylabel('Probability Density')
plt.title(f'Normal Distribution Fit for Customer Age (μ={mu:.2f}, σ={sigma:.2f})')
